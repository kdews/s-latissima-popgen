        prefix="$4"
        dep_jobid="$5"
        trailing_args=( "${@:6}" )
        # Create log directory named after prefix
        logdir="$(make_logdir "$prefix")"
        # Job submission
        cmd=(
            sbatch
            --parsable
            -p "$partition"
            -J "$prefix"
            --array="$array_size"
            -o "$logdir/%x_%a.out"
            --dependency="afterok:$dep_jobid"
            "$sbatch_file"
            "$prefix"
            "${trailing_args[@]}"
        )
        jobid="$("${cmd[@]}")"
        echo "${cmd[*]}" >> "$pipeline_log"
    else
        # Inputs
