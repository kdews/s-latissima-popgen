# Define function to return prefix of input file
get_prefix () {
    local filename
    filename="$(basename "$1")"
    filename="${filename%.*}"
    echo "$filename"
}
# Define function to make a log directory from an input string
# (e.g., prefix) only if it doesn't already exist
make_logdir () {
    # Create log directory (if needed) from given prefix
    local logdir
    logdir="${1}_logs"
    mkdir -p "$logdir"
    echo "$logdir"
}
# Define function for array or non-array submission
# that returns the jobid but takes no dependencies
no_depend () {
    local array_size
    local sbatch_file
    local prefix
    local trailing_args
    local logdir
    local jobid
    local cmd
    # Define job type
    # Determine array size for all batch jobs (e.g., number of samples)
    if [[ "$1" = "--array" ]]
    then
        # Inputs
        array_size="$2"
        if [[ $(echo "$array_size" | sed 's/,/ /g' | wc -w) -eq 1 ]]
        then
            array_size="1-${array_size}"
        fi
        sbatch_file="$3"
        prefix="$4"
        trailing_args=( "${@:5}" )
        # Create log directory named after prefix
        logdir="$(make_logdir "$prefix")"
        # Job submission
        cmd=(
            sbatch
            --parsable
            -p "$partition"
            -J "$prefix"
            --array="$array_size"
            -o "$logdir/%x_%a.out"
            "$sbatch_file"
            "$prefix"
            "${trailing_args[@]}"
        )
        jobid="$("${cmd[@]}")"
        echo "${cmd[*]}" >> "$pipeline_log"
    else
        # Inputs
        sbatch_file="$1"
        prefix="$2"
        trailing_args=( "${@:3}" )
        # Create log directory named after prefix
        logdir="$(make_logdir "$prefix")"
        # Job submission
        cmd=(
            sbatch
            --parsable
            -p "$partition"
            -J "$prefix"
            -o "$logdir/%x_%j.out"
            "$sbatch_file"
            "$prefix"
            "${trailing_args[@]}"
        )
        jobid="$("${cmd[@]}")"
        echo "${cmd[*]}" >> "$pipeline_log"
    fi
    echo "$jobid"
}
